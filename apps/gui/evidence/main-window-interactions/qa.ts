/// Mounts the review queue and drives one accept through the production
/// listener, so the captured receipt is the screen's real outcome rendering.
///
/// The projection the intent result carries is the one Core would have
/// republished for that outcome, never the pending queue with a different
/// receipt pinned to it: a confirmed verdict comes *from* `ReviewRequestUpdated`,
/// so by the time the outcome is confirmed the review is already settled. A
/// pending verdict leaves the review pending because Core has not answered yet,
/// and a rejected one leaves it pending because Core refused the command
/// outright — both of those are the real post-send state.
async function mountD2Review(outcome: D2IntentResult["outcome"]): Promise<void> {
  const pending = await d2Review();
  const settled = outcome.state === "confirmed" ? await d2ReviewDecided() : pending;
  renderD2Decisions(
    root!,
    pending,
    async () => ({
      projection: settled,
      pendingCommandId: outcome.state === "pending" ? "gui-d2-review" : null,
      outcome,
    }),
    locale,
  );
  const note = await waitFor<HTMLTextAreaElement>("[data-d2-review-feedback]");
  if (note) {
    // Typed through the real input listener, so the captured note is what the
    // production draft handling produces.
    note.value = "Replay evidence matches the recorded bindings.";
    note.dispatchEvent(new Event("input", { bubbles: true }));
  }
  click("[data-d2-action='accept_review']");
}

