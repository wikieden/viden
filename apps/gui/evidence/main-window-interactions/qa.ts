interface CockpitOptions {
  projection: D1CockpitProjection;
  /** Present so the rail's gear opens the Settings overlay. */
  preferencesAvailable?: boolean;
  /** Rejects instead of hanging, for the recovery-alert state. */
  d6Rejects?: boolean;
  /** Present so the command palette's `Jump to` section resolves. */
  crossLane?: boolean;
  /** Present so the command palette's `Files` section resolves. */
  files?: boolean;
  /** Present so the titlebar selector and the rail footer open the picker. */
  projectPicker?: boolean;
  /** The `WorkspaceDiffLoaded` page the DiffReview entry points resolve to. */
  workspaceDiff?: WorkspaceDiffProjection;
  /**
   * The `OperatorGitActionFinished` answer the commit bar resolves to.
   *
   * Present makes the bar and the titlebar sync chip live; absent leaves both
   * in their unbound-host shape, which is a different capture.
   */
  operatorGit?: OperatorGitProjection;
}

function mountCockpit(options: CockpitOptions): void {
  const { projection } = options;
  renderD1Cockpit(
    root!,
    projection,
    never<D1IntentResult>,
    never<D1IntentResult>,
    never<unknown>,
    never<D6RecoveryProjection>,
    {
      // No timers: the capture must not move while the operator frames it.
      poll: false,
      showWelcome: false,
      onNavigate: () => undefined,
      sendComposerControl: (_intent: ComposerControlIntent, _laneId: string | null) =>
        never<D1IntentResult>(),
      sendD6Intent: options.d6Rejects
        ? () => Promise.reject(new Error(D6_REJECTION))
        : () => never<D6IntentResult>(),
      loadPaletteCrossLane: options.crossLane
        ? async () => PALETTE_CROSS_LANE
        : undefined,
      loadPaletteFiles: options.files ? async () => PALETTE_FILES : undefined,
      // The same read pair the shell injects: `read` answers the capability
      // and the staleness check with no Core traffic, `query` answers the
      // actual `QueryWorkspaceDiff`. Both resolve to one fixed page, so the
      // capture cannot move after it settles.
      workspaceDiff: options.workspaceDiff
        ? {
            read: async () => options.workspaceDiff!,
            query: async () => options.workspaceDiff!,
          }
        : undefined,
      // The same triple the shell injects. Every call resolves to one fixed
      // answer, so the capture cannot move after it settles — including the
      // pending states, whose answer is itself "still pending".
      operatorGit: options.operatorGit
        ? {
            read: async () => options.operatorGit!,
            run: async () => options.operatorGit!,
            poll: async () => options.operatorGit!,
          }
        : undefined,
      loadRecentWork: options.projectPicker ? async () => RECENT_WORK : undefined,
      // The chooser never resolves, so `Add directory…` cannot advance the
      // capture past the columns it is framing.
      onPickProjectFolder: options.projectPicker ? () => never<string | null>() : undefined,
      onOpenWorkspace: options.projectPicker ? () => never<void>() : undefined,
      preferences:
        options.preferencesAvailable === undefined
          ? undefined
          : {
              isAvailable: async () => options.preferencesAvailable === true,
              save: () => never<PreferenceIntentOutcome>(),
              restore: () => never<PreferenceIntentOutcome>(),
            },
    },
  );
}

